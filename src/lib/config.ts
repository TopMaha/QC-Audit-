/**
 * ตั้งค่าการเชื่อมต่อระบบหลังบ้าน
 *
 * ถ้าไม่ได้ตั้ง VITE_API_URL แอปจะทำงานแบบ "โหมดในเครื่อง" เหมือนเดิมทุกประการ
 * (ข้อมูลอยู่ใน localStorage) จึงเปิดดู/พัฒนาได้โดยไม่ต้องมี Worker
 */

const raw = (import.meta.env.VITE_API_URL ?? '').trim();

/** ที่อยู่ API โดยตัด / ท้ายออก เพื่อให้ต่อ path ได้โดยไม่เกิด // ซ้อน */
export const API_URL = raw.replace(/\/+$/, '');

/**
 * โทเคนสำหรับเรียก API
 *
 * ⚠️ ค่านี้ถูกฝังลงไฟล์ JavaScript ตอน build ผู้ใช้ที่เปิดหน้าเว็บจึงอ่านได้
 * เป็นข้อจำกัดของการยืนยันตัวตนแบบเบาที่เลือกใช้ (แอปใช้ภายในโรงงาน)
 * ไม่ได้กันคนนอกที่เข้าถึงหน้าเว็บได้ — ถ้าต้องการกันจริงต้องมีระบบล็อกอินฝั่งเซิร์ฟเวอร์
 */
export const AUTH_TOKEN = (import.meta.env.VITE_AUTH_TOKEN ?? '').trim();

/**
 * โทเคนต้องเป็นอักขระ ASCII ติดกัน ไม่มีช่องว่าง
 * เคยตั้ง secret ผิดเป็นข้อความอธิบายภาษาไทย — ใส่ลง header ไม่ได้ fetch ล้มก่อนส่ง
 * หน้าจอเลยขึ้นว่าไม่มีเน็ตทั้งที่ต่ออยู่ จึงตรวจไว้ตรงนี้ให้บอกสาเหตุจริง
 */
export const AUTH_TOKEN_OK = /^[\x21-\x7e]*$/.test(AUTH_TOKEN);
if (!AUTH_TOKEN_OK) {
  console.error('VITE_AUTH_TOKEN ไม่ใช่โทเคน (มีช่องว่างหรืออักษรที่ไม่ใช่ ASCII) — ตั้งค่าใหม่แล้ว build ใหม่');
}

/** ต่อระบบหลังบ้านจริงหรือไม่ */
export const ONLINE_MODE = API_URL !== '';
